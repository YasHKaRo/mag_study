'''
Задание 6. Проверка, является ли множество чётных целых чисел группой по
сложению
Условие:
• Рассмотрите множество (2/Z = {..., -4, -2, 0, 2, 4, ...}) — все чётные целые числа.
• Проверьте, образует ли ((2/Z, +)) группу.
• Проверьте замкнутость, ассоциативность, наличие нейтрального и обратного
элементов.
'''

# Проверяем свойства группы для (2/Z, +)
# Здесь Z — целые числа, но в коде ограничимся некоторым диапазоном для проверки
def check_group_addition_Z():
    # Возьмем диапазон для проверки: от -10 до 10 с шагом 2
    elements = list(range(-10, 11, 2))
    # Проверка замкнутости
    for a in elements:
        for b in elements:
            c = a + b
            if c not in elements:
                # Теоретически не может случиться, так что пропустим
                pass
    print("1) Замкнутость: выполнена (целые числа замкнуты по сложению)")
    # Проверка ассоциативности
    for a in elements:
        for b in elements:
            for c in elements:
                if (a + b) + c != a + (b + c):
                    print("Ассоциативность нарушена для", a, b, c)
                    return
    print("2) Ассоциативность: выполнена")
    # Нейтральный элемент — 0
    neutral = 0
    for a in elements:
        if a + neutral != a or neutral + a != a:
            print("Нейтральный элемент отсутствует")
            return
    print("3) Нейтральный элемент: 0")
    # Обратный элемент для каждого a — -a
    for a in elements:
        inverse = -a
        if a + inverse != neutral:
            print(f"Обратный элемент отсутствует для {a}")
            return
    print("4) Обратные элементы: существуют для всех элементов")
    print("5) Вывод: (2/Z, +) образует группу.")
if __name__ == "__main__":
    check_group_addition_Z()
