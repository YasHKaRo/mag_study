print("=" * 70)
print("ЗАДАНИЕ 4: Оценка параметров по обучающей выборке")
print("Использование байесовского классификатора с оцененными параметрами")
print("=" * 70)

# ------------ 1. ОБУЧАЮЩАЯ ВЫБОРКА ------------
print("\n1. ОБУЧАЮЩАЯ ВЫБОРКА:")

# Класс A1: 5 объектов, 2 признака
data_A1 = np.array([
    [1.2, 2.3],  # Объект 1 класса A1
    [1.5, 2.1],  # Объект 2 класса A1
    [1.8, 2.5],  # Объект 3 класса A1
    [1.3, 2.0],  # Объект 4 класса A1
    [1.6, 2.4]  # Объект 5 класса A1
])

# Класс A2: 5 объектов, 2 признака
data_A2 = np.array([
    [3.1, 1.2],  # Объект 1 класса A2
    [3.5, 1.5],  # Объект 2 класса A2
    [3.2, 1.3],  # Объект 3 класса A2
    [3.8, 1.1],  # Объект 4 класса A2
    [3.4, 1.4]  # Объект 5 класса A2
])

print(f"Класс A1: {len(data_A1)} объектов, размерность: {data_A1.shape[1]}")
print(f"Класс A2: {len(data_A2)} объектов, размерность: {data_A2.shape[1]}")
print("Каждый объект: [признак₁, признак₂]")

# ------------ 2. ОЦЕНКА ВЕКТОРОВ СРЕДНИХ ------------
print("\n" + "=" * 70)
print("2. ОЦЕНКА ВЕКТОРОВ СРЕДНИХ:")
print("=" * 70)

# Формула оценки: m_i = (1/N_i) * Σ x_k, где x_k ∈ A_i
m1 = np.mean(data_A1, axis=0)  # Среднее по столбцам (axis=0) для класса A1
m2 = np.mean(data_A2, axis=0)  # Среднее по столбцам (axis=0) для класса A2

print(f"\nКласс A1:")
print(f"  Исходные данные:\n{np.round(data_A1, 2)}")
print(f"  Оценка вектора средних:")
print(f"  m₁ = (1/{len(data_A1)}) * Σ x_k = [{m1[0]:.4f}, {m1[1]:.4f}]ᵀ")
print(f"  Упрощенно: m₁ = [{m1[0]:.2f}, {m1[1]:.2f}]ᵀ")

print(f"\nКласс A2:")
print(f"  Исходные данные:\n{np.round(data_A2, 2)}")
print(f"  Оценка вектора средних:")
print(f"  m₂ = (1/{len(data_A2)}) * Σ x_k = [{m2[0]:.4f}, {m2[1]:.4f}]ᵀ")
print(f"  Упрощенно: m₂ = [{m2[0]:.2f}, {m2[1]:.2f}]ᵀ")

# Геометрическая интерпретация
print(f"\nИнтерпретация:")
print(f"- m₁ находится ближе к точкам с координатами ~(1.5, 2.3)")
print(f"- m₂ находится ближе к точкам с координатами ~(3.4, 1.3)")
print(f"- Разность: m₂ - m₁ = [{m2[0] - m1[0]:.2f}, {m2[1] - m1[1]:.2f}]")
print(f"  (классы хорошо разделены по первому признаку)")

# ------------ 3. ОЦЕНКА КОВАРИАЦИОННЫХ МАТРИЦ ------------
print("\n" + "=" * 70)
print("3. ОЦЕНКА КОВАРИАЦИОННЫХ МАТРИЦ:")
print("=" * 70)

# Формула оценки: C_i = (1/(N_i-1)) * Σ (x_k - m_i)(x_k - m_i)^T
# np.cov() автоматически использует несмещенную оценку (делит на N-1)
C1 = np.cov(data_A1.T)  # Транспонируем, потому что np.cov ожидает признаки в строках
C2 = np.cov(data_A2.T)  # Аналогично для класса A2

print(f"\nКласс A1:")
print("Ковариационная матрица C₁:")
print(np.round(C1, 4))
print(f"\nДиагональные элементы (дисперсии):")
print(f"  Var(x₁) = {C1[0, 0]:.4f}  (разброс по первому признаку)")
print(f"  Var(x₂) = {C1[1, 1]:.4f}  (разброс по второму признаку)")
print(f"Несимметричный элемент (ковариация):")
print(f"  Cov(x₁,x₂) = {C1[0, 1]:.4f}  (связь между признаками)")
print(f"Определитель |C₁| = {np.linalg.det(C1):.6f}")

print(f"\nКласс A2:")
print("Ковариационная матрица C₂:")
print(np.round(C2, 4))
print(f"\nДиагональные элементы (дисперсии):")
print(f"  Var(x₁) = {C2[0, 0]:.4f}  (разброс по первому признаку)")
print(f"  Var(x₂) = {C2[1, 1]:.4f}  (разброс по второму признаку)")
print(f"Несимметричный элемент (ковариация):")
print(f"  Cov(x₁,x₂) = {C2[0, 1]:.4f}  (связь между признаками)")
print(f"Определитель |C₂| = {np.linalg.det(C2):.6f}")

print(f"\nСравнение матриц:")
print(f"1. C1 и C2 имеют РАЗНЫЕ значения (общей матрицы нет)")
print(f"2. В C1 дисперсия по x₂ ({C1[1, 1]:.4f}) > дисперсии по x₁ ({C1[0, 0]:.4f})")
print(f"3. В C2 дисперсии более сбалансированы")
print(f"4. Ковариации маленькие, признаки слабо коррелированы")

# ------------ 4. АПРИОРНЫЕ ВЕРОЯТНОСТИ ------------
print("\n" + "=" * 70)
print("4. АПРИОРНЫЕ ВЕРОЯТНОСТИ:")
print("=" * 70)

P1 = 0.5  # P(A₁) - задано в условии
P2 = 0.5  # P(A₂) - задано в условии

print(f"\nЗаданные априорные вероятности:")
print(f"P(A₁) = {P1}, P(A₂) = {P2}")
print(f"\nИнтерпретация:")
print("- Классы считаются РАВНОВЕРОЯТНЫМИ")
print("- Классификатор не имеет предпочтений до наблюдения признаков")
print(f"- Логарифмы: ln(P(A₁)) = ln(P(A₂)) = {np.log(P1):.4f}")

# ------------ 5. ПОСТРОЕНИЕ КЛАССИФИКАТОРА ------------
print("\n" + "=" * 70)
print("5. ПОСТРОЕНИЕ БАЙЕСОВСКОГО КЛАССИФИКАТОРА:")
print("=" * 70)

# Создаем экземпляр классификатора
classifier = BayesianClassifier()

# Добавляем класс A1 с ОЦЕНЕННЫМИ параметрами
classifier.add_class('A1', P1, m1, C1)
print(f"\nДобавлен класс A1:")
print(f"  m₁ = [{m1[0]:.4f}, {m1[1]:.4f}]ᵀ")
print(f"  |C₁| = {np.linalg.det(C1):.6f}")

# Добавляем класс A2 с ОЦЕНЕННЫМИ параметрами
classifier.add_class('A2', P2, m2, C2)
print(f"\nДобавлен класс A2:")
print(f"  m₂ = [{m2[0]:.4f}, {m2[1]:.4f}]ᵀ")
print(f"  |C₂| = {np.linalg.det(C2):.6f}")

print(f"\nКлассификатор готов к работе!")
print(f"Количество классов: {len(classifier.classes)}")
print("ВАЖНО: Классификатор использует РАЗНЫЕ ковариационные матрицы")

# ------------ 6. КЛАССИФИКАЦИЯ НОВЫХ НАБЛЮДЕНИЙ ------------
print("\n" + "=" * 70)
print("6. КЛАССИФИКАЦИЯ НОВЫХ НАБЛЮДЕНИЙ:")
print("=" * 70)

# Тестовые наблюдения из условия задачи
test_samples = [
    np.array([2.0, 2.0]),  # x⁽¹⁾
    np.array([2.5, 1.8])  # x⁽²⁾
]

print("\nТестовые наблюдения:")
for i, x in enumerate(test_samples, 1):
    print(f"\nНаблюдение {i}: x = [{x[0]}, {x[1]}]ᵀ")
    print(f"  Геометрически: находится между классами")
    print(f"  Ближе к A1 по: [{m1[0] - x[0]:.2f}, {m1[1] - x[1]:.2f}]")
    print(f"  Ближе к A2 по: [{m2[0] - x[0]:.2f}, {m2[1] - x[1]:.2f}]")

print("\nРезультаты классификации:")

for i, x in enumerate(test_samples, 1):
    # Получаем предсказание и значения дискриминантных функций
    pred, scores = classifier.predict(x)

    print(f"\n{x} Наблюдение {i}: x = [{x[0]}, {x[1]}]ᵀ")
    print("-" * 40)

    print("Значения дискриминантных функций:")
    print(f"  g_A1(x) = {scores['A1']:.4f}")
    print(f"  g_A2(x) = {scores['A2']:.4f}")

    # Определяем, какой класс "выиграл" и с каким преимуществом
    diff = scores['A1'] - scores['A2']
    if diff > 0:
        winner = 'A1'
        advantage = diff
    else:
        winner = 'A2'
        advantage = -diff

    print(f"\nСравнение:")
    print(f"  g_A1(x) - g_A2(x) = {diff:.4f}")
    print(f"  Преимущество класса {winner}: {advantage:.4f}")

    print(f"\nРешение классификатора: x → {pred}")

    # Объяснение решения
    if pred == 'A1':
        print(f"  Почему A1? Точка ближе к m₁ [{m1[0]:.2f}, {m1[1]:.2f}], чем к m₂ [{m2[0]:.2f}, {m2[1]:.2f}]")
    else:
        print(f"  Почему A2? Точка ближе к m₂ [{m2[0]:.2f}, {m2[1]:.2f}], чем к m₁ [{m1[0]:.2f}, {m1[1]:.2f}]")

# ------------ 7. КРОСС-ВАЛИДАЦИЯ LEAVE-ONE-OUT ------------
print("\n" + "=" * 70)
print("7. КРОСС-ВАЛИДАЦИЯ LEAVE-ONE-OUT:")
print("=" * 70)

# Объединяем все данные и создаем метки классов
all_data = np.concatenate((data_A1, data_A2), axis=0)  # Объединенная выборка
labels = np.array([1] * 5 + [2] * 5)  # Метки: 1 для A1, 2 для A2

n = len(all_data)  # Общее количество объектов (10)
correct = 0  # Счетчик правильных классификаций

print(f"\nМетод: Leave-One-Out Cross-Validation (LOOCV)")
print(f"Всего объектов: {n} (5 из A1, 5 из A2)")
print(f"Количество итераций: {n} (каждый объект по очереди становится тестовым)")

print("\nПроцесс валидации:")
for i in range(n):
    # Шаг 1: Создаем обучающую выборку без i-го объекта
    train_data = np.delete(all_data, i, axis=0)  # Удаляем i-ю строку
    train_labels = np.delete(labels, i)  # Удаляем i-ю метку

    # Шаг 2: Разделяем обучающую выборку по классам
    data1_loo = train_data[train_labels == 1]  # Объекты класса A1
    data2_loo = train_data[train_labels == 2]  # Объекты класса A2

    # Шаг 3: Оцениваем параметры по уменьшенной выборке
    m1_loo = np.mean(data1_loo, axis=0)
    m2_loo = np.mean(data2_loo, axis=0)
    C1_loo = np.cov(data1_loo.T)
    C2_loo = np.cov(data2_loo.T)

    # Шаг 4: Создаем классификатор с оцененными параметрами
    clf_loo = BayesianClassifier()
    clf_loo.add_class('A1', 0.5, m1_loo, C1_loo)
    clf_loo.add_class('A2', 0.5, m2_loo, C2_loo)

    # Шаг 5: Тестируем на i-м объекте
    x_test = all_data[i]  # Текущий тестовый объект
    true_class = 'A1' if labels[i] == 1 else 'A2'  # Истинный класс
    pred_class, _ = clf_loo.predict(x_test)  # Предсказанный класс

    # Шаг 6: Проверяем правильность
    if pred_class == true_class:
        correct += 1
        status = "✓ ПРАВИЛЬНО"
    else:
        status = "✗ ОШИБКА"

    # Выводим информацию о текущей итерации
    if i < 2 or i == n - 1:  # Показываем первые 2 и последнюю итерацию
        print(f"\nИтерация {i + 1}:")
        print(f"  Тестовый объект: [{x_test[0]:.1f}, {x_test[1]:.1f}] (истинный класс: {true_class})")
        print(f"  Обучающих объектов: {len(train_data)}")
        print(f"  Предсказанный класс: {pred_class}")
        print(f"  Результат: {status}")

# Вычисляем точность
accuracy = correct / n

print("\n" + "=" * 70)
print("РЕЗУЛЬТАТЫ КРОСС-ВАЛИДАЦИИ:")
print("=" * 70)

print(f"\nОбщая статистика:")
print(f"Правильно классифицировано: {correct} из {n}")
print(f"Ошибок: {n - correct}")

print(f"\nТочность классификации:")
print(f"Accuracy = correct / total = {correct} / {n} = {accuracy:.4f}")
print(f"В процентах: {accuracy * 100:.1f}%")

print(f"\nОшибка классификации:")
print(f"Error rate = 1 - accuracy = {1 - accuracy:.4f}")
print(f"В процентах: {(1 - accuracy) * 100:.1f}%")

print(f"\nИнтерпретация:")
if accuracy >= 0.9:
    print("Отличная точность! Модель хорошо обобщает данные.")
elif accuracy >= 0.7:
    print("Хорошая точность. Модель адекватно описывает данные.")
else:
    print("Средняя точность. Возможно, нужны больше данных или другие признаки.")

print(f"\nВАЖНО: Точность {accuracy * 100:.1f}% оценивает, насколько хорошо")
print("модель будет работать на НОВЫХ данных, не участвовавших в обучении.")

print("\n" + "=" * 70)
print("ЗАДАНИЕ 4 ВЫПОЛНЕНО УСПЕШНО!")
print("=" * 70)

print("\nКлючевые выводы:")
print("1. Параметры модели (m_i, C_i) успешно оценены по обучающей выборке")
print("2. Классификатор правильно распознает тестовые наблюдения")
print(f"3. Кросс-валидация показала точность {accuracy * 100:.1f}%")
print("4. Метод leave-one-out дает надежную оценку обобщающей способности")
print("5. Байесовский подход позволяет строить классификаторы")
print("   даже при небольшом количестве обучающих данных")